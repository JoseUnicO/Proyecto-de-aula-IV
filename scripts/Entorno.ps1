param([string]$Base='biblioteca')
$ErrorActionPreference='Stop'
$perfil=Join-Path $env:LOCALAPPDATA "Biblioteca\$Base"
$archivo='conexion.xml'
$cred=Import-Clixml -LiteralPath (Join-Path $perfil $archivo)
$env:BIBLIOTECA_DB_NAME=$Base
$env:BIBLIOTECA_DB_USER=$cred.UserName
$env:BIBLIOTECA_DB_PASSWORD=$cred.GetNetworkCredential().Password
$env:JAVA_HOME='C:\Program Files\Java\jdk-26.0.2.1'
$env:Path="$env:JAVA_HOME\bin;$env:Path"
